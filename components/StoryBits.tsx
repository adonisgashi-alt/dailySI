import type { Story } from "@/lib/desk";
import type { Art } from "@/lib/images";
import { ago } from "@/lib/format";

export function ArtFigure({ art, caption = true }: { art: Art; caption?: boolean }) {
  return (
    <figure>
      <div className="art">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={art.src} alt={art.alt} loading="lazy" decoding="async" referrerPolicy="no-referrer" />
        <span className="tag">{art.kind === "generated" ? "◇ Generated" : "Illustrative"}</span>
      </div>
      {caption && (
        <figcaption>
          {art.kind === "photo" ? (
            <>
              {art.sourceUrl ? <a href={art.sourceUrl} target="_blank" rel="noopener noreferrer">{art.credit}</a> : art.credit}
              {art.license && (
                <>
                  {" · "}
                  {art.licenseUrl ? <a href={art.licenseUrl} target="_blank" rel="noopener noreferrer">{art.license}</a> : art.license}
                </>
              )}
            </>
          ) : (
            "Thumbnail generated by The Daily SI"
          )}
        </figcaption>
      )}
    </figure>
  );
}

export function VerifiedBadge({ story }: { story: Story }) {
  return story.status === "confirmed" ? (
    <span className="badge ok" title={story.basis}>✓ Confirmed · {story.outlets.length} {story.outlets.length === 1 ? "source" : "sources"}</span>
  ) : (
    <span className="badge pending" title={story.basis}>◌ Verifying</span>
  );
}

export function StoryMeta({ story, now }: { story: Story; now: number }) {
  return (
    <div className="meta">
      <span>{ago(story.lastUpdate, now)}</span>
      <span>·</span>
      <span>{story.outlets.slice(0, 3).join(", ")}{story.outlets.length > 3 ? ` +${story.outlets.length - 3}` : ""}</span>
      <span title={`Confidence ${story.confidence}%`} aria-label={`Confidence ${story.confidence}%`}>
        <span className="conf"><i style={{ width: `${story.confidence}%` }} /></span>
      </span>
    </div>
  );
}
